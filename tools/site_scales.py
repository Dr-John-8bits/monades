# Writes the scale list of site/index.html and site/manuel/index.html (between the gammes markers) from app/dsp/scale_table.inc,
# in the order and with the names of the FM-1 screen: python3 tools/site_scales.py
import re
from pathlib import Path
R=Path(__file__).resolve().parents[1];T=(R/'app/dsp/scale_table.inc').read_text();site=R/'site/index.html'
families=re.search(r'scale_families\[\]=\{([^}]*)\}',T).group(1).replace('"','').split(',')
twelve=[(n,int(f),up!=down) for n,f,up,down in re.findall(r'\{"([^"]+)",(\d+),(0x[0-9a-f]+),(0x[0-9a-f]+)\}',T)]
micro=[(n,int(f),False) for n,f in re.findall(r'\{"([^"]+)",(\d+),\d+,[\d.]+f,',T)]
order=[int(x) for x in re.search(r'scale_order\[\]=\{([^}]*)\}',T).group(1).split(',')]
scales=twelve+micro;assert len(order)==len(scales)
groups={}
for k in order:
 n,f,split=scales[k];groups.setdefault(f,[]).append(n+('*' if split else ''))
rows=''.join(f'      <tr><td>{families[f]} ({len(v)})</td><td>{" · ".join(v)}</td></tr>\n' for f,v in groups.items())
block=(f'<!-- gammes: generated by tools/site_scales.py -->\n'
 f'    <details class="scales" id="gammes"><summary>Les {len(scales)} gammes, dans l\'ordre de K2 sur HARMONY</summary>\n'
 f'    <table class="manual">\n      <tr><th>Famille</th><th>Gammes</th></tr>\n{rows}    </table>\n'
 f'    <p>* Montée et descente différentes. ~ Approchée sur les 12 demi-tons. Les familles MAQAM 1/4, MICROTONAL et SCALA sont microtonales.</p>\n    </details>\n    <!-- /gammes -->')
for page in (site,R/'site/manuel/index.html'): # the home page and the full manual
 s=page.read_text();s,n=re.subn(r'<!-- gammes:.*?<!-- /gammes -->',lambda m:block,s,flags=re.S);assert n==1,f'markers missing in {page}'
 page.write_text(s)
print(len(scales),'scales,',len(groups),'families')
