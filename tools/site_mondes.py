# Writes the list of the 91 Mondes into site/manuel/index.html (between the mondes markers), from presets/catalog.json
# (written by tools/generate_presets.py) and app/dsp/scale_table.inc: number and family as on the FM-1 screen, the
# FDDS Mondes with their name, scale, root note, tempo and the six tracks' engines.  python3 tools/site_mondes.py
import json,re
from pathlib import Path
R=Path(__file__).resolve().parents[1]
cat=json.loads((R/'presets/catalog.json').read_text());T=(R/'app/dsp/scale_table.inc').read_text()
twelve=re.findall(r'\{"([^"]+)",\d+,0x[0-9a-f]+,0x[0-9a-f]+\}',T);micro=re.findall(r'\{"([^"]+)",\d+,\d+,[\d.]+f,',T)
scales=twelve+micro
families=cat['family_short'];assert len(cat['biomes'])==91
ENGINES=['PLAITS KICK','PLAITS SNARE','PLAITS HAT','PLAITS FM','PLAITS VA','RINGS MODAL','PLAITS HARMONIC','SINE CHOIR','ROUND BASS','ELEMENTS STRIKE','MELLOW DRIFT','SATIN MORPH']
NOTES=['C','C#','D','D#','E','F','F#','G','G#','A','A#','B']
rows=[]
for i,b in enumerate(cat['biomes']):
 fam=families[b['family']].upper()
 label=f'{i+1} {b["name"].upper()}' if fam=='FDDS' else f'{i+1} {fam}'
 eng=' · '.join(f'{k+1} {ENGINES[t["model"]]}'+(' (coupée)' if t['mute'] else '') for k,t in enumerate(b['tracks']))
 rows.append(f'      <tr><td>{label}</td><td>{scales[b["scale"]]} · {NOTES[b["root"]%12]} · {b["tempo"]}&nbsp;BPM</td><td>{eng}</td></tr>\n')
block=('<!-- mondes: generated by tools/site_mondes.py -->\n  <div class="tablewrap"><table><tr><th>Monde (écran)</th><th>Gamme · note · tempo</th><th>Moteurs des six pistes</th></tr>\n'
       +''.join(rows)+'  </table></div>\n  <!-- /mondes -->')
page=R/'site/manuel/index.html';s=page.read_text()
s,n=re.subn(r'<!-- mondes:.*?<!-- /mondes -->',lambda m:block,s,flags=re.S);assert n==1,f'markers missing in {page}'
page.write_text(s);print(len(rows),'Mondes')
