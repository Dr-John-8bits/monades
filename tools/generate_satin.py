#!/usr/bin/env python3
"""Original Fourier tables: four rounded shapes, four anti-aliasing bands."""
from pathlib import Path
import math
R=Path(__file__).resolve().parents[1]
rows=['/* Generated by tools/generate_satin.py; MIT OR GPL-3.0-only. */', 'static const float satin_table[4][4][257]={']
for cap in (1,2,4,8):
 rows.append('{')
 for shape in range(4):
  coeff=[(1.0 if h==1 else 0.0) if shape==0 else ((-1)**((h-1)//2)/h**2 if h%2 else 0) if shape==1 else (1/h**1.8 if h%2 else 0) if shape==2 else (-1)**(h+1)/h**1.8 for h in range(1,9)]
  # Same gain in every band; crossfades never boost a changing fundamental.
  gain=1/sum(abs(x) for x in coeff)
  vals=[gain*sum(coeff[h-1]*math.sin(2*math.pi*h*i/256) for h in range(1,cap+1)) for i in range(256)]
  vals.append(vals[0]);rows.append('{'+','.join(f'{x:.9f}f' for x in vals)+'},')
 rows.append('},')
rows.append('};')
(R/'app/dsp/satin_tables.inc').write_text('\n'.join(rows)+'\n')
